"""Create the locally served Chinese body fonts from upstream Noto Sans SC.

Run: python -I scripts/subset-body-font.py /path/to/NotoSansSC.ttf
Requires fonttools and brotli. Normal website builds do not require Python.
The original opening and its fonts are independent of this subset.
"""
import argparse
import hashlib
import io
import json
import re
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
SOURCE_URL = 'https://cdn.jsdelivr.net/gh/google/fonts@main/ofl/notosanssc/NotoSansSC%5Bwght%5D.ttf'
LICENSE_URL = 'https://github.com/google/fonts/blob/main/ofl/notosanssc/OFL.txt'
CJK = re.compile(r'[\u2e80-\u9fff\uf900-\ufaff\uff00-\uffef]')


def characters(text):
    return set(CJK.findall(text))


def unicode_ranges(chars):
    points = sorted(ord(char) for char in chars)
    groups = []
    first = last = points[0]
    for point in points[1:]:
        if point == last + 1:
            last = point
        else:
            groups.append((first, last))
            first = last = point
    groups.append((first, last))
    return ','.join(f'U+{a:X}' + (f'-{b:X}' if a != b else '') for a, b in groups)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--output-dir', type=Path, default=ROOT / 'src/brand')
    args = parser.parse_args()
    sources = ['src/FieldJournal.jsx', 'src/CommunityIdentity.jsx', 'src/commons-stories.js', 'src/main.jsx', 'src/GenesisHero.jsx', 'src/SiteHeader.jsx', 'src/CinematicHome.jsx', 'src/InstitutionWall.jsx', 'src/PlanetScene.jsx', 'src/HomeLanguage.jsx', 'src/home-copy.js', 'src/community.jsx', 'src/journal-content.json']
    core = characters(''.join((ROOT / name).read_text() for name in sources))
    data_text = (ROOT / 'src/community-data.json').read_text()
    data = json.loads(data_text)
    # Follow the curated first page. The remaining characters are loaded only
    # when additional excerpts or expanded discussions make them necessary.
    journal = json.loads((ROOT / 'src/journal-content.json').read_text())
    highlights = list(dict.fromkeys(value for value in journal.get('discussionHighlights', [])
                                   if isinstance(value, int) and not isinstance(value, bool)
                                   and 0 < value <= len(data['discussions'])))
    order = highlights + [value for value in range(1, len(data['discussions']) + 1) if value not in highlights]
    for value in order[:3]:
        item = data['discussions'][value - 1]
        core |= characters(item['question'] + item['tag'] + item['quote'])
    # Research directions also show questions from the archive on first load.
    for topic in journal['topics']:
        core |= characters(data['discussions'][topic['discussionId'] - 1]['question'])
    all_chars = core | characters(data_text)
    source_bytes = args.source.read_bytes()
    font = TTFont(args.source)
    missing = sorted(c for c in all_chars if ord(c) not in font.getBestCmap())
    if missing:
        raise ValueError('Upstream font lacks these characters: ' + ''.join(missing))
    if set(a.axisTag for a in font['fvar'].axes) != {'wght'}:
        raise ValueError('Expected the single-weight-axis Noto Sans SC source')
    version = font['name'].getDebugName(5)
    options = subset.Options()
    options.name_IDs = ['*']
    options.name_legacy = True
    options.name_languages = ['*']
    options.layout_features = ['*']
    options.notdef_outline = True
    selection = subset.Subsetter(options=options)
    selection.populate(unicodes=[ord(c) for c in all_chars])
    selection.subset(font)
    font = instantiateVariableFont(font, {'wght': (400, 600)}, inplace=True, updateFontNames=True)
    # Serializing between the two subset passes restores empty variation
    # records after the weight-axis instancing pass.
    buffer = io.BytesIO()
    font.save(buffer)
    subset_bytes = buffer.getvalue()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    css = ['/* Generated by scripts/subset-body-font.py; keep the Unicode ranges with their fonts. */']
    chunks = []
    for name, chars in [('core', core), ('archive', all_chars - core)]:
        part = TTFont(io.BytesIO(subset_bytes))
        selection = subset.Subsetter(options=options)
        selection.populate(unicodes=[ord(c) for c in chars])
        selection.subset(part)
        if not all(ord(c) in part.getBestCmap() for c in chars):
            raise ValueError('Incomplete subset: ' + name)
        filename = f'noto-sans-sc-{name}.woff2'
        path = args.output_dir / filename
        part.flavor = 'woff2'
        part.save(path)
        css.append("@font-face {\n  font-family: 'AgentHub Sans SC';\n  font-style: normal;\n  font-weight: 400 600;\n  font-display: swap;\n  src: url('./" + filename + "') format('woff2');\n  unicode-range: " + unicode_ranges(chars) + ";\n}")
        chunks.append({'file': filename, 'bytes': path.stat().st_size, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(), 'characters': ''.join(sorted(chars))})
    (args.output_dir / 'noto-sans-sc.css').write_text('\n\n'.join(css) + '\n')
    metadata = {
        'family': 'Noto Sans SC', 'source': SOURCE_URL, 'license': LICENSE_URL,
        'upstream_version': version, 'source_sha256': hashlib.sha256(source_bytes).hexdigest(),
        'weight_range': [400, 600], 'source_files': sources + ['src/community-data.json'],
        'notes': 'Local WOFF2 subsets with unchanged outlines and a restricted weight axis. Copyright, license and attribution name records retained. Unicode ranges are disjoint. Characters added later retain system fallback until this script is rerun.',
        'chunks': chunks,
    }
    (args.output_dir / 'noto-sans-sc-source.json').write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({'characters': len(all_chars), 'chunks': [{k: item[k] for k in ['file', 'bytes']} for item in chunks]}, ensure_ascii=False))


if __name__ == '__main__':
    main()
